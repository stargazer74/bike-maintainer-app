/** No dynamic colour on purpose: the app keeps the workshop look of the web app. */
@Composable
fun BikeMaintainerTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit,
) {
    CompositionLocalProvider(LocalStatusColors provides if (darkTheme) DarkStatusColors else LightStatusColors) {
        MaterialTheme(
            colorScheme = if (darkTheme) DarkColorScheme else LightColorScheme,
            typography = Typography,
            content = content,
        )
    }
}

/**
 * Background of every screen. Sets LocalContentColor to onBackground, so text on screens without a Scaffold/Surface
 * of their own stays readable in dark mode (otherwise it would be the default black).
 */
@Composable
fun AppSurface(content: @Composable () -> Unit) {
    Surface(modifier = Modifier.fillMaxSize(), color = MaterialTheme.colorScheme.background) {
        Box(Modifier.fillMaxSize()) {
            // The logo, large and very faint, behind every screen (the Scaffolds are transparent for it).
            val dark = MaterialTheme.colorScheme.background.luminance() < 0.5f
            Image(
                painter = painterResource(if (dark) R.drawable.welcome_logo_dark else R.drawable.welcome_logo_light),
                contentDescription = null,
                alpha = if (dark) 0.05f else 0.06f,
                modifier = Modifier.fillMaxWidth(0.85f).align(Alignment.Center),
            )
            content()
        }
    }
}
